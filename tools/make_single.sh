#!/bin/sh
# Builds main_single.cpp (one-file submission) from include/ and src/.
# Headers are emitted in dependency order, then the sources; local
# #include "..." lines and #pragma once are dropped. Writes to stdout.
set -e
cd "$(dirname "$0")/.."

HEADERS="Models.h Graph.h Coloring.h Backtracking.h BranchAndBound.h Scheduler.h Samples.h Console.h Tests.h MachineApi.h App.h"
SOURCES="Graph.cpp Coloring.cpp Backtracking.cpp BranchAndBound.cpp Scheduler.cpp Samples.cpp Console.cpp Tests.cpp MachineApi.cpp App.cpp main.cpp"

cat <<'EOF'
// =============================================================================
// main_single.cpp - Smart University Examination Timetable Generator
// Single-file version for submission. GENERATED by tools/make_single.sh from
// include/ and src/ - edit those files, then run `make single`.
//
// Build: g++ -std=c++17 -Wall -Wextra -O2 main_single.cpp -o timetable
// Run  : ./timetable          (menu)
//        ./timetable --test   (self-tests)
// =============================================================================
EOF

for f in $HEADERS; do
    printf '\n// ======================= include/%s =======================\n' "$f"
    grep -v -e '^#include "' -e '^#pragma once' "include/$f"
done
for f in $SOURCES; do
    printf '\n// ======================= src/%s =======================\n' "$f"
    grep -v -e '^#include "' "src/$f"
done
